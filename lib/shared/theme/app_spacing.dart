/// Shared spacing and sizes. Layout uses an 8 px grid.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;

  /// Space between the screen edge and the content.
  static const double screenMargin = 16;

  /// Corner radius of text fields and buttons.
  static const double controlRadius = 12;

  /// Corner radius of cards and dialogs.
  static const double cardRadius = 16;

  /// Minimum height of anything the user taps.
  static const double tapTarget = 48;

  /// Size of the food photos on S06.
  static const double foodImage = 56;
}
